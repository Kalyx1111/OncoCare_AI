def load_sessions():
    if SESSIONS_DB.exists():
        with open(SESSIONS_DB, "r") as f:
            return json.load(f)
    return {}

def save_session(session_id, data):
    sessions = load_sessions()
    sessions[session_id] = {**data, "updated": datetime.datetime.now().isoformat()}
    with open(SESSIONS_DB, "w") as f:
        json.dump(sessions, f, indent=2)

def load_chat():
    if CHAT_DB.exists():
        with open(CHAT_DB, "r") as f:
            return json.load(f)
    return {"messages": [], "doctors": []}

def save_chat(msg):
    chat = load_chat()
    chat["messages"].append({**msg, "id": str(uuid.uuid4()), "timestamp": datetime.datetime.now().isoformat()})
    chat["messages"] = chat["messages"][-500:]  # Keep last 500
    with open(CHAT_DB, "w") as f:
        json.dump(chat, f, indent=2)

def extract_pdf_text(filepath):
    if not FITZ_OK:
        return "[PDF extraction unavailable — PyMuPDF not installed]"
    try:
        doc = fitz.open(str(filepath))
        text = ""
        for page in doc:
            text += page.get_text()
        doc.close()
        return text[:8000]  # Limit for API context
    except Exception as e:
        return f"[PDF extraction error: {e}]"

def extract_image_info(filepath):
    if not PIL_OK:
        return "[Image analysis unavailable — Pillow not installed]"
    try:
        img = Image.open(str(filepath))
        return f"Image: {img.format}, {img.size[0]}x{img.size[1]}px, Mode: {img.mode}"
    except Exception as e:
        return f"[Image error: {e}]"

