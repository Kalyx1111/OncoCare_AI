@app.route("/api/upload", methods=["POST"])
def upload():
    if "files" not in request.files:
        return jsonify({"error": "No files in request"}), 400

    results = []
    session_id = request.form.get("session_id") or str(uuid.uuid4())
    session_dir = UPLOAD_DIR / session_id
    session_dir.mkdir(parents=True, exist_ok=True)

    for f in request.files.getlist("files"):
        if not f.filename:
            continue
        ext = Path(f.filename).suffix.lower()
        safe_name = f"{uuid.uuid4().hex}{ext}"
        dest = session_dir / safe_name
        f.save(str(dest))
        size = dest.stat().st_size

        # Extract content for analysis
        extracted = ""
        file_type = "unknown"
        if ext == ".pdf":
            extracted = extract_pdf_text(dest)
            file_type = "pdf"
        elif ext in [".jpg", ".jpeg", ".png", ".bmp", ".tiff", ".dcm"]:
            extracted = extract_image_info(dest)
            file_type = "image"
        elif ext in [".txt", ".csv"]:
            try:
                extracted = dest.read_text(encoding="utf-8", errors="ignore")[:5000]
            except:
                extracted = ""
            file_type = "text"

        results.append({
            "original_name": f.filename,
            "saved_as": safe_name,
            "size_bytes": size,
            "size_kb": round(size / 1024, 1),
            "type": file_type,
            "extension": ext,
            "extracted_preview": extracted[:300] if extracted else "",
            "has_content": bool(extracted)
        })
        log.info(f"Uploaded: {f.filename} → {safe_name} ({size} bytes)")

    # Save session
    existing = load_sessions().get(session_id, {})
    existing_files = existing.get("files", [])
    existing_files.extend(results)
    save_session(session_id, {
        "session_id": session_id,
        "files": existing_files,
        "created": existing.get("created", datetime.datetime.now().isoformat())
    })

    return jsonify({
        "success": True,
        "session_id": session_id,
        "uploaded": len(results),
        "files": results,
        "disclaimer": DISCLAIMER
    })

